import matplotlib.pyplot as plt
import seaborn as sns

def show_boxplots(data, title):
    # Automatically select numeric columns
    num_cols = data.select_dtypes(include="number").columns

    if len(num_cols) == 0:
        print("Error: No numeric columns found in the dataset.")
        return

    # Create a flexible grid based on the number of columns
    n_cols = 3
    n_rows = (len(num_cols) + n_cols - 1) // n_cols

    fig, axes = plt.subplots(
        n_rows, n_cols,
        figsize=(13, 4 * n_rows)
    )

    # Make axes a flat array
    axes = axes.flatten() if hasattr(axes, "flatten") else [axes]

    for i, col in enumerate(num_cols):
        sns.boxplot(y=data[col].dropna(), ax=axes[i], color="skyblue")
        axes[i].set_title(col)
        axes[i].set_ylabel("")

    # Hide any unused plots
    for j in range(len(num_cols), len(axes)):
        axes[j].set_visible(False)

    fig.suptitle(title, fontsize=15)
    plt.tight_layout()
    plt.show()

